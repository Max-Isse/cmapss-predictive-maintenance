"""Drive the SYNTHETIC REPLAY end to end: emit a batch -> bronze (new files only) -> stream into silver and gold.

Writes reports/tables/replay_batches.csv (one row per replay batch, appended across runs) and reports/replay.md
with the batch log and the check that the incremental tables equal a full recomputation (generated; do not edit).
"""

from __future__ import annotations

import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd
from pyspark.sql import SparkSession
from pyspark.sql import functions as F

from cmapss_pm.config import Config
from cmapss_pm.features.gold import gold_path
from cmapss_pm.ingest.bronze import ingest_landing
from cmapss_pm.ingest.replay import emit_batch, load_state
from cmapss_pm.pipeline.incremental import run_stream, verify_incremental


def run_replay(spark: SparkSession, cfg: Config, batches: int) -> list[dict[str, Any]]:
    log: list[dict[str, Any]] = []
    for _ in range(batches):
        started = time.perf_counter()
        batch = emit_batch(cfg)
        if batch is None:
            break
        ingested = ingest_landing(spark, cfg, batch.files)
        ingest_done = time.perf_counter()
        streamed = run_stream(spark, cfg)
        by_rule: dict[str, int] = {}
        for s in streamed:
            for rule, n in s["quarantine_by_rule"].items():
                by_rule[rule] = by_rule.get(rule, 0) + n
        row = {
            "batch": batch.batch,
            "finished_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "files": len(batch.files),
            "rows_delivered": batch.rows,
            "engines_delivered": batch.engines,
            "late_held": batch.late_held,
            "late_released": batch.late_released,
            "bronze_inserted": sum(r.rows_inserted for r in ingested),
            "micro_batches": len(streamed),
            "engines_recomputed": sum(s["engines"] for s in streamed),
            "quarantined_after": sum(by_rule.values()),
            "quarantine_by_rule": ";".join(f"{k}={v}" for k, v in sorted(by_rule.items())),
            "seconds": round(time.perf_counter() - started, 1),
            "ingest_seconds": round(ingest_done - started, 1),
            "stream_seconds": round(time.perf_counter() - ingest_done, 1),
            "replay_finished": batch.finished,
        }
        log.append(row)
        out = cfg.path("tables_dir") / "replay_batches.csv"
        out.parent.mkdir(parents=True, exist_ok=True)
        frame = pd.DataFrame([row])
        if out.exists():
            frame = pd.concat([pd.read_csv(out), frame], ignore_index=True)
        frame.to_csv(out, index=False)
        if batch.finished:
            break
    return log


def write_replay_report(spark: SparkSession, cfg: Config) -> tuple[Path, dict[str, Any]]:
    check = verify_incremental(spark, cfg)
    gold = spark.read.format("delta").load(gold_path(cfg, "features"))
    coverage = (
        gold.where(F.col("split").isin("test", "replay"))
        .groupBy("dataset")
        .pivot("split", ["test", "replay"])
        .agg(F.count(F.lit(1)))
        .orderBy("dataset")
        .toPandas()
        .fillna(0)
    )
    coverage["replayed_share"] = coverage["replay"] / coverage["test"]
    batches_csv = cfg.path("tables_dir") / "replay_batches.csv"
    batches = pd.read_csv(batches_csv) if batches_csv.exists() else pd.DataFrame()
    state = load_state(cfg)
    ok = check["silver_mismatches"] == check["quarantine_mismatches"] == check["gold_mismatches"] == 0
    show = batches.drop(columns=["finished_at"], errors="ignore")
    text = f"""<!-- GENERATED by `cmapss replay` - do not edit by hand. -->
# SYNTHETIC REPLAY: incremental bronze -> silver -> gold

**SYNTHETIC REPLAY.** The values are the real NASA test-engine rows, delivered verbatim; *when* they arrive is
simulated: {cfg.section("replay")["cycles_per_batch"]} cycles per engine per batch, all engines starting together,
and {cfg.section("replay")["late_rows"]} rows per batch held back to the next batch (a deliberate late-arrival
disturbance). Design: D-018, D-019; code: `src/cmapss_pm/ingest/replay.py`, `src/cmapss_pm/pipeline/`.

Batches emitted so far: {state.next_batch - 1}; late rows waiting: {len(state.held)}.

## Batch log (`reports/tables/replay_batches.csv`)

`quarantined_after` counts the quarantine rows of the engines recomputed in that batch: rows after a late (held)
row are quarantined as `sequence_gap`, and released again when the late row arrives one batch later.

{show.to_markdown(index=False) if len(show) else "_no batches yet_"}

## Incremental tables = full recomputation: **{"PASSED" if ok else "FAILED"}**

Silver, quarantine and gold maintained batch by batch, compared row for row (`exceptAll` both ways, run ids
excluded) with silver, quarantine and gold recomputed in memory from the whole bronze table.

| table | rows | mismatched rows |
|---|---|---|
| silver.cycles | {check["silver_rows"]:,} | {check["silver_mismatches"]} |
| silver.quarantine (cycles) | {check["quarantine_rows"]:,} | {check["quarantine_mismatches"]} |
| gold.features | {check["gold_rows"]:,} | {check["gold_mismatches"]} |

Feature spec versions in gold: {", ".join(f"`{v}`" for v in check["spec_versions_in_gold"])} (one version: replayed
rows use the spec fitted on training engines, never refitted).

## Replay coverage in gold (rows)

{coverage.to_markdown(index=False, floatfmt=".3f")}
"""
    path = cfg.path("reports_dir") / "replay.md"
    path.write_text(text, encoding="utf-8")
    return path, {**check, "passed": ok}
