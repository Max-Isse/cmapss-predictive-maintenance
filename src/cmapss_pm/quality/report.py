"""Per-run data-quality report: row counts per layer, quarantine by rule, contract and reconciliation checks.

Writes reports/data_quality/<run_id>.md, reports/data_quality/latest.md and appends one row per run to
reports/data_quality/runs.csv (generated; do not edit).
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd
from pyspark.sql import SparkSession

from cmapss_pm.config import Config
from cmapss_pm.quality.silver import SilverResult, silver_path


def _md(df: pd.DataFrame) -> str:
    return str(df.to_markdown(index=False)) if len(df) else "_none_"


def checks_table(res: SilverResult, contract_errors: list[dict[str, Any]]) -> pd.DataFrame:
    c = res.counts
    rows = [
        (
            "bronze cycles = silver + quarantine",
            c["bronze_cycles"] == c["silver_cycles"] + c["quarantine_cycles"],
            f"{c['bronze_cycles']:,} = {c['silver_cycles']:,} + {c['quarantine_cycles']:,}",
        ),
        (
            "bronze RUL = silver + quarantine",
            c["bronze_rul"] == c["silver_rul"] + c["quarantine_rul"],
            f"{c['bronze_rul']:,} = {c['silver_rul']:,} + {c['quarantine_rul']:,}",
        ),
        (
            "every validated test engine has a RUL",
            res.rul_checks["test_engines_without_rul"] == 0,
            f"{res.rul_checks['test_engines_without_rul']} test engines without RUL",
        ),
        (
            "pandera contract: silver.cycles and silver.rul",
            not contract_errors,
            f"{len(contract_errors)} failed checks",
        ),
    ]
    return pd.DataFrame(rows, columns=["check", "passed", "detail"])


def write_report(spark: SparkSession, cfg: Config, res: SilverResult, contract_errors: list[dict[str, Any]]) -> Path:
    out_dir = cfg.path("reports_dir") / "data_quality"
    out_dir.mkdir(parents=True, exist_ok=True)
    checks = checks_table(res, contract_errors)
    counts = pd.DataFrame([{"layer_table": k, "rows": v} for k, v in res.counts.items()])
    rules = pd.DataFrame([{"rule": k, "rows": v} for k, v in sorted(res.quarantine_by_rule.items())])
    engines = pd.DataFrame(res.engines)
    q = spark.read.format("delta").load(silver_path(cfg, "quarantine"))
    sample = (
        q.select("source_table", "dataset", "split", "unit", "cycle", "rule", "reason")
        .orderBy("rule", "dataset", "split", "unit", "cycle")
        .limit(20)
        .toPandas()
    )
    status = "PASSED" if bool(checks["passed"].all()) else "FAILED"
    text = f"""<!-- GENERATED by `cmapss silver` - do not edit by hand. -->
# Data-quality report: {res.run_id}

Run started {res.started:%Y-%m-%d %H:%M:%S} UTC. Overall status: **{status}**.
Rules and their order: `src/cmapss_pm/quality/silver.py`; contract: `src/cmapss_pm/quality/contract.py`.

## Checks

{_md(checks)}

## Row counts per layer

{_md(counts)}

## Quarantined rows by rule

{_md(rules)}

## Silver engines per dataset and split

{_md(engines)}

## Contract failures

{_md(pd.DataFrame(contract_errors))}

## Quarantine sample (up to 20 rows)

{_md(sample)}
"""
    (out_dir / f"{res.run_id}.md").write_text(text, encoding="utf-8")
    (out_dir / "latest.md").write_text(text, encoding="utf-8")
    run_row = pd.DataFrame(
        [
            {
                "run_id": res.run_id,
                "written_at": datetime.now(UTC).isoformat(timespec="seconds"),
                "status": status,
                **res.counts,
                **{f"q_{k}": v for k, v in res.quarantine_by_rule.items()},
            }
        ]
    )
    runs = out_dir / "runs.csv"
    if runs.exists():
        run_row = pd.concat([pd.read_csv(runs), run_row], ignore_index=True)
    run_row.to_csv(runs, index=False)
    return out_dir / f"{res.run_id}.md"
